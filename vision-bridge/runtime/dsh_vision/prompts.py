def focus_hint(hint):
    """构造 focus hint 片段；截尾 500 字符，声明只用于判断重点。"""
    if not hint or not isinstance(hint, str):
        return ''
    text = hint.strip()
    if not text:
        return ''
    if len(text) > HINT_MAX_CHARS:
        text = text[:HINT_MAX_CHARS]
    return '重点（只用于判断重点，与图无关请忽略）：' + text


def language_directive(language):
    lang = (language or '').strip() or os.environ.get('DSH_VISION_LANGUAGE', '')
    return lang
